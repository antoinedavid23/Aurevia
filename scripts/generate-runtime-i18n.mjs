import { writeFile } from "node:fs/promises";
import { createServer } from "vite";

const server = await createServer({ configFile: false, server: { middlewareMode: true }, appType: "custom" });

try {
  const [core, supplemental, publicCopy, generated, reviewed, audit, quality] = await Promise.all([
    server.ssrLoadModule("/lib/i18n-source.ts"),
    server.ssrLoadModule("/lib/i18n-supplement.ts"),
    server.ssrLoadModule("/lib/i18n-public.ts"),
    server.ssrLoadModule("/lib/i18n-generated.ts"),
    server.ssrLoadModule("/lib/i18n-reviewed.ts"),
    server.ssrLoadModule("/lib/i18n-audit-fixes.ts"),
    server.ssrLoadModule("/lib/i18n-quality.ts"),
  ]);

  const merged = {
    ...generated.generatedMessages,
    ...core.messages,
    ...supplemental.supplementalMessages,
    ...publicCopy.publicMessages,
    ...reviewed.reviewedMessages,
    ...audit.auditFixMessages,
    ...quality.qualityMessages,
  };
  const runtime = Object.fromEntries(
    Object.entries(merged).map(([source, value]) => [source, { it: value.it, en: value.en }]),
  );
  const content = `// Generated by scripts/generate-runtime-i18n.mjs.\n` +
    `// Only the three public languages are shipped to visitors: FR keys, IT and EN values.\n` +
    `export const runtimeMessages: Record<string, { it: string; en: string }> = ${JSON.stringify(runtime)};\n`;
  await writeFile(new URL("../lib/i18n-runtime.ts", import.meta.url), content, "utf8");
} finally {
  await server.close();
}
